"""EarthContact: inventory existing imported meshes and assign obvious roles.

Run INSIDE Unreal Editor via Tools > Execute Python Script. Requires Python Editor
Script Plugin. Never moves, renames, deletes or edits any model.
Writes Config/ImportedAssets.ini and Saved/EarthContactAssetInventory.txt.

If a role is ambiguous, it stays unassigned; inspect the inventory and
adjust only the INI when needed. Run again after importing more assets.
"""
import os
import re
import unreal

ROOT = unreal.Paths.project_dir()
CONFIG = os.path.join(ROOT, "Config", "ImportedAssets.ini")
REPORT = os.path.join(ROOT, "Saved", "EarthContactAssetInventory.txt")
registry = unreal.AssetRegistryHelpers.get_asset_registry()
records = []
for entry in registry.get_assets_by_path("/Game", recursive=True):
    cls = str(entry.asset_class_path.asset_name)
    if cls not in ("SkeletalMesh", "StaticMesh"):
        continue
    name = str(entry.asset_name)
    path = str(entry.package_name) + "." + name
    folder = str(entry.package_path)
    records.append(dict(path=path, folder=folder, name=name, type=cls))
records.sort(key=lambda x: x["path"].lower())

def is_match(entry, positive, negative=()):
    text = (entry["folder"] + "/" + entry["name"]).lower()
    return any(re.search(p, text) for p in positive) and not any(re.search(n, text) for n in negative)

roles = {
    "Grey": ("SkeletalMesh", [r"grey", r"\bgray\b", r"alien"], [r"nordic", r"boss", r"monster", r"reptil", r"baby", r"skinwalker", r"truck", r"ufo"]),
    "MonsterLeader": ("SkeletalMesh", [r"monster", r"boss", r"reptil", r"skinwalker"], [r"baby", r"grey", r"gray"]),
    "CrashedUFO": ("StaticMesh", [r"crash", r"wreck", r"damaged", r"broken"], [r"truck", r"car", r"rock", r"building"]),
    "IntactUFO": ("StaticMesh", [r"ufo", r"saucer", r"spaceship", r"spacecraft", r"disc", r"craft"], [r"crash", r"wreck", r"damaged", r"broken"]),
    "Dog": ("SkeletalMesh", [r"dog", r"canine", r"hound"], []),
}
chosen = {}
details = []
for role, (kind, yes, no) in roles.items():
    possible = [r for r in records if r["type"] == kind and is_match(r, yes, no)]
    if len(possible) == 1:
        chosen[role] = possible[0]["path"]
        details.append(role + " = " + chosen[role])
    elif possible:
        chosen[role] = ""
        details.append(role + " = AMBIGUOUS (" + str(len(possible)) + " candidates)")
        details.extend("    " + x["path"] for x in possible)
    else:
        chosen[role] = ""
        details.append(role + " = NOT FOUND")

os.makedirs(os.path.dirname(REPORT), exist_ok=True)
with open(REPORT, "w", encoding="utf-8") as f:
    f.write("EARTHCONTACT - ASSET INVENTORY\n")
    f.write("Generated by Unreal Editor; local files were not changed.\n\n")
    f.write("AUTO-MAPPING\n" + "\n".join(details) + "\n\n")
    f.write("ALL SKELETAL/STATIC MESHES IN /GAME (" + str(len(records)) + ")\n")
    for item in records:
        f.write(item["type"] + " | " + item["path"] + "\n")

# Keep any hand-edited nonblank mapping, rather than overwriting the user's choice.
prior = {}
if os.path.exists(CONFIG):
    for raw in open(CONFIG, encoding="utf-8-sig"):
        if "=" in raw and not raw.lstrip().startswith((";", "#")):
            k, v = raw.split("=", 1)
            if k.strip() in roles and v.strip():
                prior[k.strip()] = v.strip()
for name in roles:
    chosen[name] = prior.get(name, chosen[name])

with open(CONFIG, "w", encoding="utf-8") as f:
    f.write("; Generated by Tools/scan_imported_assets.py inside Unreal Editor\n")
    f.write("; Use /Game/.../Mesh.Mesh references; edit paths here if detection is ambiguous.\n")
    f.write("[EarthContact.ImportedAssets]\n")
    for name, path in chosen.items():
        f.write(name + "=" + path + "\n")
unreal.log_warning("EARTHCONTACT: scanned " + str(len(records)) + " meshes")
for line in details:
    unreal.log_warning("EARTHCONTACT: " + line)
unreal.log_warning("EARTHCONTACT: inventory at " + REPORT)
unreal.log_warning("EARTHCONTACT: mapping at " + CONFIG)
